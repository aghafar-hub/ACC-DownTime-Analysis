// Joins the backend files into ONE file, so the Apps Script editor needs a single paste.
//
//   node tools/bundle-apps-script.mjs [outFile]      (default: local-data/ACC_Downtime_Backend.gs)
//
// The order is the one the backend tests use: Schema first, then the rest alphabetically.
// The result is generated code: never edit it, and never commit it.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'backend/apps-script');
const out = resolve(process.argv[2] || resolve(root, 'local-data/ACC_Downtime_Backend.gs'));

const files = readdirSync(dir)
  .filter((f) => f.endsWith('.js'))
  .sort((a, b) => (a === 'Schema.js' ? -1 : b === 'Schema.js' ? 1 : a.localeCompare(b)));

const parts = [
  '// ACC Downtime Analysis - backend (generated by tools/bundle-apps-script.mjs).',
  '// Paste this whole file into the Apps Script editor as Code.gs. Do not edit it by hand.',
  `// Files joined, in order: ${files.join(', ')}`,
  '',
];
for (const f of files) {
  parts.push(`// ======================================================================`, `// ${f}`, `// ======================================================================`, readFileSync(resolve(dir, f), 'utf8').replace(/\s+$/, ''), '');
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, parts.join('\n'));
console.log(`Wrote ${out} (${files.length} files, ${parts.join('\n').length} characters)`);
