const db = buildSyntheticDb();
const startup: Startup = {
  lines: db.lines, areas: db.areas, equipment: db.equipment, equipment_areas: db.equipment_areas, aliases: db.aliases,
  classifications: db.classifications, reasons: db.reasons, settings: db.settings, years: [2026, 2025],
};
const asOf = dataRangeOf(db.events.filter((r) => !r.is_void))!.to;
const run = (setup: ReportSetup, rows: EventRow[] = db.events): ReportModel =>
  buildReport({ setup, startup, rows, asOf, generatedAt: '2026-10-13 11:05', generatedBy: 'Tester Ünï', plant: 'Sokhna' });
const get = <T extends SectionModel['id']>(m: ReportModel, id: T): Extract<SectionModel, { id: T }> => m.sections.find((s) => s.id === id) as Extract<SectionModel, { id: T }>;
const sheet = async (bytes: Uint8Array, name: string): Promise<unknown[][]> => {
  const r = await readXlsxSheet(bytes, name);
  if (!r.ok) throw new Error(`${name}: ${r.reason}`);
  return r.data;
};
/** a report cell as the sheet holds it: percentages are fractions, empty is null */
const expectedCell = (kind: ReportTable['columns'][number]['kind'], v: string | number | null): unknown => {
  if (v === null || v === '') return null;
  if (typeof v === 'number' && kind === 'pct') return v / 100;
  return v;
};
function expectTableMatches(data: unknown[][], table: ReportTable, dateCols: Record<number, 'date' | 'datetime'> = {}) {
  expect(data[0]).toEqual(table.columns.map((c) => c.label));
  table.rows.forEach((row, ri) => {
    const got = data[1 + ri] ?? [];
    row.forEach((v, ci) => {
      const kind = table.columns[ci]!.kind;
      let want = expectedCell(kind, v);
      if (dateCols[ci] && typeof v === 'string') want = serialOfStamp(v) ?? v;
      const cell = got[ci] ?? null;
      if (typeof want === 'number') expect(cell, `row ${ri} col ${ci} (${table.columns[ci]!.label})`).toBeCloseTo(want, 9);
      else expect(cell, `row ${ri} col ${ci} (${table.columns[ci]!.label})`).toEqual(want);
    });
  });
  if (table.total) {
    const got = data[1 + table.rows.length] ?? [];
    table.total.forEach((v, ci) => {
      const want = expectedCell(table.columns[ci]!.kind, v);
      const cell = got[ci] ?? null;
      if (typeof want === 'number') expect(cell).toBeCloseTo(want, 9);
      else expect(cell).toEqual(want);
    });
  }
}

describe('report workbook', () => {
  const model = run(defaultSetup('monthly'));
  const wb = buildReportWorkbook(model);

  it('Summary first, then one sheet per chosen section that holds a table; names valid, unique, at most 31 characters', async () => {
    const r = await readXlsxSheet(wb.bytes, 'Summary');
    if (!r.ok) throw new Error('summary');
    expect(r.sheets).toEqual(wb.sheets);
    expect(r.sheets[0]).toBe('Summary');
    expect(r.sheets).toHaveLength(1 + SECTION_ORDER.length - 1); // every section but the cover
    for (const n of r.sheets) {
      expect(n.length).toBeLessThanOrEqual(31);
      expect(n).not.toMatch(/[\\/?*[\]:]/);
    }
    expect(new Set(r.sheets.map((n) => n.toLowerCase())).size).toBe(r.sheets.length);
    expect(r.sheets).toContain(SHEET_TITLES.pareto);
    expect(r.sheets).toContain(SHEET_TITLES.classes);
  });

  it('Summary sheet: title, plant, period, comparison, filters, who and when, data coverage, scope and the sections list', async () => {
    const data = await sheet(wb.bytes, 'Summary');
    const kv = new Map(data.filter((r) => r.length >= 2).map((r) => [r[0], r[1]]));
    expect(kv.get('Report')).toBe('Monthly management report');
    expect(kv.get('Plant')).toBe('Sokhna');
    expect(kv.get('Period')).toBe('2026-09-01 to 2026-09-30');
    expect(String(kv.get('Comparison'))).toContain('Previous period');
    expect(String(kv.get('Comparison'))).toContain('2026-08-01 to 2026-08-31');
    expect(kv.get('Filters')).toBe(model.filterSummary);
    expect(kv.get('Generated by')).toBe('Tester Ünï');
    expect(kv.get('Generated on')).toBe(serialOfStamp('2026-10-13 11:05'));
    expect(kv.get('Data coverage')).toBe(`${model.coverage!.from} to ${model.coverage!.to}`);
    expect(kv.get('Events in scope')).toBe(model.scope.events);
    expect(kv.get('Area-hours in scope')).toBeCloseTo(model.scope.areaHours, 9);
    expect(kv.get('Availability basis')).toBe(model.basis);
    // the list of sections maps each report section to its sheet
    const at = data.findIndex((r) => r[0] === 'Sections');
    const listed = data.slice(at + 1).map((r) => [r[0], r[1]]);
    expect(listed).toHaveLength(SECTION_ORDER.length - 1);
    expect(listed.map((x) => x[1])).toEqual(wb.sheets.slice(1));
    expect(listed[0]![0]).toBe(get(model, 'summary').title);
  });

  it('every section\'s sheet carries the report\'s own table, cell for cell', async () => {
    for (const id of ['monthly', 'area_downtime', 'availability', 'mtbf_mttr', 'failure_rate', 'top_equipment', 'top_reasons', 'repeats', 'quadrant', 'quality'] as const) {
      const s = get(model, id) as Extract<SectionModel, { data: { table: ReportTable } }>;
      const data = await sheet(wb.bytes, SHEET_TITLES[id]);
      expectTableMatches(data, s.data.table);
    }
    expectTableMatches(await sheet(wb.bytes, SHEET_TITLES.longest), get(model, 'longest').data.table, { 1: 'datetime' });
    expectTableMatches(await sheet(wb.bytes, SHEET_TITLES.events), get(model, 'events').data.table, { 0: 'datetime' });
  });

  it('daily: every plotted day; classes: month by classification with the totals row; pareto: the three charts in one table; when: the hour by weekday grid', async () => {
    const daily = get(model, 'daily').data;
    const d = await sheet(wb.bytes, SHEET_TITLES.daily);
    expect(d[0]).toEqual(['Day', 'Failure h', 'Planned h', 'CIR h', 'Total h', `${daily.rollingDays}-day average h`]);
    daily.days.forEach((p, i) => {
      expect(d[1 + i]![0]).toBe(serialOfStamp(p.date));
      if (p.hasData) {
        expect(d[1 + i]![4]).toBeCloseTo(p.downtimeHours, 9);
        if (p.rollingDowntimeHours === null) expect(d[1 + i]![5] ?? null).toBeNull();
        else expect(d[1 + i]![5]).toBeCloseTo(p.rollingDowntimeHours, 9);
      } else expect(d[1 + i]![4] ?? null).toBeNull();
    });
    expect(daily.days.filter((x) => x.hasData).reduce((a, p) => a + p.downtimeHours, 0)).toBeCloseTo(daily.total, 9);

    const classes = get(model, 'classes').data;
    const c = await sheet(wb.bytes, SHEET_TITLES.classes);
    expect(c[0]).toEqual(['Month', 'PRO h', 'MEC h', 'ELE h', 'AUT h', 'PL h', 'CIR h', 'Total h']);
    const totalRow = c[1 + classes.months.length]!;
    expect(totalRow[0]).toBe('Total');
    expect(totalRow[7]).toBeCloseTo(classes.totals.reduce((a, x) => a + x.hours, 0), 9);
    const sumMonths = classes.months.reduce((a, m) => a + (m.hasData ? m.total : 0), 0);
    expect(totalRow[7]).toBeCloseTo(sumMonths, 6);

    const pareto = get(model, 'pareto').data;
    const p = await sheet(wb.bytes, SHEET_TITLES.pareto);
    expect(p[0]![0]).toBe('Chart');
    const nRows = pareto.parts.reduce((a, x) => a + x.table.rows.length, 0);
    expect(p.slice(1, 1 + nRows)).toHaveLength(nRows);
    expect(p[1]![0]).toBe(pareto.parts[0]!.title);
    expect(p[1]![2]).toBeCloseTo(pareto.parts[0]!.table.rows[0]![1] as number, 9);

    const heat = get(model, 'when').data.heat!;
    const w = await sheet(wb.bytes, SHEET_TITLES.when);
    expect(w[0]).toEqual(['Hour', ...heat.cols.map((x) => x.label), 'Total']);
    const grand = w[1 + heat.rows.length]!;
    expect(grand[grand.length - 1]).toBe(heat.total);
    expect(w[1]!.slice(1, 1 + heat.cols.length)).toEqual(heat.values[0]);
  });

  it('executive summary: the KPI strip numbers (availability, RF and UF as percentages) and the key findings', async () => {
    const s = get(model, 'summary').data;
    const e = await sheet(wb.bytes, SHEET_TITLES.summary);
    expect(e[0]![0]).toBe('Measure');
    s.kpis.forEach((k, i) => {
      expect(e[1 + i]![0]).toBe(k.label);
      expect(e[1 + i]![1]).toBe(k.text);
      const want = k.value === null ? null : ['availability', 'reliability', 'utilization'].includes(k.id) ? k.value * 100 : k.value;
      if (want === null) expect(e[1 + i]![2] ?? null).toBeNull();
      else expect(e[1 + i]![2]).toBeCloseTo(want, 9);
    });
    const flat = e.flat();
    for (const b of s.bullets) expect(flat).toContain(b);
  });

  it('timestamps and numbers have the wanted formats in the file (0.0 hours, 0.0% availability, dates)', async () => {
    const { unzipSync, strFromU8 } = await import('fflate');
    const files = unzipSync(wb.bytes);
    const styles = strFromU8(files['xl/styles.xml']!);
    for (const code of ['0.0', '0.00', '0.0%', 'yyyy-mm-dd', 'yyyy-mm-dd hh:mm:ss']) expect(styles).toContain(`formatCode="${code}"`);
  });
});

describe('report workbook with other setups', () => {
  it('only the chosen sections get a sheet; filters show on the Summary sheet and numbers follow the filter', async () => {
    const area = db.areas.find((a) => a.active && a.in_downtime_sheet)!.area_id;
    const setup: ReportSetup = { ...defaultSetup('custom'), sections: ['summary', 'monthly', 'area_downtime'], filters: { ...defaultSetup('custom').filters, areaIds: [area] }, preset: 'last3', compare: false };
    const m = run(setup);
    const wb = buildReportWorkbook(m);
    expect(wb.sheets).toEqual(['Summary', SHEET_TITLES.summary, SHEET_TITLES.monthly, SHEET_TITLES.area_downtime]);
    const kv = new Map((await sheet(wb.bytes, 'Summary')).filter((r) => r.length >= 2).map((r) => [r[0], r[1]]));
    expect(kv.get('Filters')).toBe(`Area ${area}`);
    expect(kv.get('Comparison')).toBe('No comparison');
    const rows = await sheet(wb.bytes, SHEET_TITLES.area_downtime);
    expect(rows[1]![0]).toBe(area);
    expect(rows[1]![4]).toBeCloseTo(get(m, 'area_downtime').data.rows[0]!.total, 9);
    expect(wb.fileName).toBe(`ACC-downtime-custom_${m.range.from}_to_${m.range.to}.xlsx`);
  });

  it('a period with no data still gives a valid workbook: sheets say why instead of showing zeros', async () => {
    const m = run({ ...defaultSetup('monthly'), preset: 'custom', from: '2030-01-01', to: '2030-01-31' });
    const wb = buildReportWorkbook(m);
    const data = await sheet(wb.bytes, SHEET_TITLES.monthly);
    expect(data.flat().some((x) => typeof x === 'string' && x.length > 20)).toBe(true);
    const kv = new Map((await sheet(wb.bytes, 'Summary')).filter((r) => r.length >= 2).map((r) => [r[0], r[1]]));
    expect(kv.get('Note')).toBeTruthy();
  });
});

describe('report CSV', () => {
  const model = run(defaultSetup('monthly'));

  it('lists the sections that hold a table (not the cover or the methodology)', () => {
    const ids = csvSections(model).map((s) => s.id);
    expect(ids).toEqual(SECTION_ORDER.filter((id) => id !== 'cover' && id !== 'methodology'));
    expect(csvSections(model).find((s) => s.id === 'monthly')!.rows).toBe(get(model, 'monthly').data.table.rows.length);
  });

  it('one file per section: BOM, header, the data rows only, named after report, period and section', () => {
    const out = buildSectionCsv(model, 'monthly')!;
    const t = get(model, 'monthly').data.table;
    expect(out.fileName).toBe('ACC-downtime-monthly-management-report_2026-09_monthly-stoppage.csv');
    expect(out.text.startsWith('﻿')).toBe(true);
    const lines = out.text.slice(1).split('\r\n');
    expect(lines.pop()).toBe('');
    expect(lines).toHaveLength(1 + t.rows.length);
    expect(lines[0]).toBe(t.columns.map((c) => c.label).join(','));
    const first = lines[1]!.split(',');
    expect(first[0]).toContain(String(t.rows[0]![0]).slice(0, 3));
    expect(Number(first[1])).toBeCloseTo(t.rows[0]![1] as number, 9);
    expect(buildSectionCsv(model, 'cover')).toBeNull();
  });

  it('percentages are written as percentage points under a "(%)" header', () => {
    const out = buildSectionCsv(model, 'availability')!;
    const t = get(model, 'availability').data.table;
    const [head, firstRow] = out.text.slice(1).split('\r\n');
    expect(head).toContain('Availability (%)');
    expect(Number(firstRow!.split(',')[1])).toBeCloseTo(t.rows[0]![1] as number, 9);
  });

  it('file names for Excel and CSV share the report name and period', () => {
    expect(reportFileName(model, 'xlsx')).toBe('ACC-downtime-monthly-management-report_2026-09.xlsx');
    const failure = run(defaultSetup('failure'));
    expect(reportFileName(failure, 'xlsx')).toBe('ACC-downtime-failure-analysis_2026-09.xlsx');
    expect(sectionTable(get(model, 'cover') as SectionModel, model)).toBeNull();
  });
});
