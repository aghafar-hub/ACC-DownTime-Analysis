import { describe, expect, it } from 'vitest';
import type { EventRow, Startup } from '../api/types';
import { dataRangeOf } from '../calc';
import { buildSyntheticDb } from '../mock/synthetic';
import { buildReport, type ReportModel, type ReportTable, type SectionModel } from '../reports/model';
import { SECTION_ORDER } from '../reports/sections';
import { defaultSetup, type ReportSetup } from '../reports/setup';
import { readXlsxSheet } from '../upload/xlsxReader';
import { buildReportWorkbook, buildSectionCsv, csvSections, reportFileName, sectionTable, SHEET_TITLES } from './reportExport';
