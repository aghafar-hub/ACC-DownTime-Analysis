async function grab(page: Page, click: () => Promise<unknown>): Promise<{ name: string; bytes: Uint8Array; dl: Download }> {
  const [dl] = await Promise.all([page.waitForEvent('download'), click()]);
  const path = await dl.path();
  return { name: dl.suggestedFilename(), bytes: new Uint8Array(readFileSync(path)), dl };
}
async function sheetsOf(bytes: Uint8Array): Promise<string[]> {
  const r = await readXlsxSheet(bytes, 'Summary');
  if (!r.ok && r.reason !== 'no_sheet') throw new Error(r.reason);
  return r.sheets;
}
async function rowsOf(bytes: Uint8Array, name: string): Promise<unknown[][]> {
  const r = await readXlsxSheet(bytes, name);
  if (!r.ok) throw new Error(`${name}: ${r.reason} (${r.sheets.join(', ')})`);
  return r.data;
}
/** A small CSV reader (quotes, doubled quotes, line breaks inside quotes) for checking the downloads. */
function parseCsv(text: string): string[][] {
  const out: string[][] = [];
  let row: string[] = [];
  let cur = '';
  let q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i]!;
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { cur += '"'; i++; } else q = false; } else cur += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(cur); cur = ''; } else if (c === '\r' && text[i + 1] === '\n') { row.push(cur); out.push(row); row = []; cur = ''; i++; } else cur += c;
  }
  if (cur || row.length) { row.push(cur); out.push(row); }
  return out;
}
/** The 'Events shown' tile once the search box has settled (the list follows the typing a moment later). */
async function settledCount(page: Page): Promise<string> {
  let last = '';
  for (let i = 0; i < 40; i++) {
    const now = (await page.getByTestId('tile-shown').innerText()).match(/[\d,]+/)![0];
    if (now === last) return now;
    last = now;
    await page.waitForTimeout(350);
  }
  return last;
}
const num = (s: string): number => parseFloat(s.replace(/,/g, ''));

